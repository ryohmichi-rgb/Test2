#
# 定義をテーブルではなくコードに置くのは BadgeCatalog と同じ考え方。
# 人物像は列で表せるものではなく、seed に入れて管理画面から編集させる類でもない。
#
# key は reference_stats.label と対応させる。参考ステータスのカードから
# 「この人に聞く」で入るため。7ラベルのうち人物はこの4つだけで、残る3つ
# （高校受験・難関高校受験・中学卒業レベル）は目標であって人ではないので持たせない。
